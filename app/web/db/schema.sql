-- Esquema Postgres (Neon) da Escala de Voluntários.
-- Pode ser executado mais de uma vez: só cria o que falta.
-- As posições do mapa e da ficha não ficam no banco: são fixas em shared/catalog.ts.

CREATE TABLE IF NOT EXISTS volunteers (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             TEXT    NOT NULL UNIQUE,
    gender           TEXT    NOT NULL CHECK (gender IN ('Masculino', 'Feminino')),
    team             TEXT    NOT NULL DEFAULT '',
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    observation      TEXT,
    can_bercario     BOOLEAN NOT NULL DEFAULT FALSE,
    can_cozinha      BOOLEAN NOT NULL DEFAULT TRUE,
    can_recepcao     BOOLEAN NOT NULL DEFAULT TRUE,
    can_banheiro     BOOLEAN NOT NULL DEFAULT TRUE,
    can_limpar_altar BOOLEAN NOT NULL DEFAULT TRUE
);

-- Contagens trazidas da planilha na carga inicial (somam com as escalas salvas).
CREATE TABLE IF NOT EXISTS history_seed (
    volunteer_id INTEGER NOT NULL REFERENCES volunteers(id) ON DELETE CASCADE,
    category     TEXT    NOT NULL,
    count        INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (volunteer_id, category)
);

CREATE TABLE IF NOT EXISTS history_position_seed (
    volunteer_id  INTEGER NOT NULL REFERENCES volunteers(id) ON DELETE CASCADE,
    position_code TEXT    NOT NULL,
    category      TEXT    NOT NULL,
    count         INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (volunteer_id, position_code)
);

-- service_date é texto AAAA-MM-DD (ordenação simples, sem fuso horário).
-- Não há índice único em (service_date, team): o banco antigo tem escalas repetidas
-- que contam no histórico; ao salvar, o sistema substitui a escala da mesma data e equipe.
CREATE TABLE IF NOT EXISTS schedules (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_date TEXT COLLATE "C" NOT NULL CHECK (service_date ~ '^\d{4}-\d{2}-\d{2}$'),
    service_type TEXT NOT NULL,
    team         TEXT NOT NULL DEFAULT '',
    notes        TEXT,
    status       TEXT NOT NULL DEFAULT 'rascunho',
    active_codes JSONB,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS schedules_date_team ON schedules (service_date, team);

CREATE TABLE IF NOT EXISTS schedule_items (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id    INTEGER NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    position_code  TEXT    NOT NULL,
    position_name  TEXT    NOT NULL,
    category       TEXT    NOT NULL,
    volunteer_id   INTEGER NOT NULL REFERENCES volunteers(id),
    volunteer_name TEXT    NOT NULL,
    item_order     INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS schedule_items_schedule ON schedule_items (schedule_id);
CREATE INDEX IF NOT EXISTS schedule_items_volunteer ON schedule_items (volunteer_id);

CREATE TABLE IF NOT EXISTS presence (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id   INTEGER NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    volunteer_id  INTEGER NOT NULL REFERENCES volunteers(id),
    confirmed     BOOLEAN NOT NULL DEFAULT FALSE,
    absent        BOOLEAN NOT NULL DEFAULT FALSE,
    justification TEXT,
    UNIQUE (schedule_id, volunteer_id)
);
CREATE INDEX IF NOT EXISTS presence_volunteer ON presence (volunteer_id);

CREATE TABLE IF NOT EXISTS app_meta (
    key   TEXT PRIMARY KEY,
    value JSONB
);

-- Quem pode usar o sistema. O login (Neon Auth) aceita cadastro de qualquer pessoa;
-- só entra quem tem o e-mail aqui (e não está suspenso).
--   admin        vê todas as equipes e gerencia esta lista pela tela Acessos
--   coordinator  vê e altera só as equipes listadas em "teams" (pelo menos uma)
CREATE TABLE IF NOT EXISTS app_users (
    email      TEXT PRIMARY KEY CHECK (email = lower(email)),
    role       TEXT NOT NULL DEFAULT 'coordinator',
    teams      TEXT[] NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by TEXT
);
-- Ajuste de bancos criados antes de existir o papel de coordenador (pode rodar de novo).
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS teams TEXT[] NOT NULL DEFAULT '{}';
ALTER TABLE app_users DROP CONSTRAINT IF EXISTS app_users_role_check;
UPDATE app_users SET role = 'coordinator' WHERE role = 'member';
ALTER TABLE app_users ALTER COLUMN role SET DEFAULT 'coordinator';
ALTER TABLE app_users ADD CONSTRAINT app_users_role_check CHECK (role IN ('admin', 'coordinator'));

-- Observações sobre um voluntário, com data e autor (o "recado" fixo continua em volunteers.observation).
CREATE TABLE IF NOT EXISTS volunteer_notes (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_id INTEGER NOT NULL REFERENCES volunteers(id) ON DELETE CASCADE,
    body         TEXT    NOT NULL CHECK (length(body) BETWEEN 1 AND 1000),
    author       TEXT    NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS volunteer_notes_volunteer ON volunteer_notes (volunteer_id, created_at DESC);

-- Registro de atividades: quem fez o quê, visto pelos administradores na tela Atividade.
--   target   o que foi mexido ("volunteer:12", "schedule:2026-12-06:Domingo_Manha_A"...)
--   repeats  gravações seguidas da mesma coisa pela mesma pessoa viram uma linha só
CREATE TABLE IF NOT EXISTS activity_log (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor    TEXT NOT NULL,
    action   TEXT NOT NULL,
    target   TEXT,
    team     TEXT,
    summary  TEXT NOT NULL,
    details  JSONB,
    repeats  INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS activity_log_at ON activity_log (id DESC);
CREATE INDEX IF NOT EXISTS activity_log_actor ON activity_log (actor, id DESC);

