/**
 * Atualização automática do banco.
 *
 * O banco é criado por db/schema.sql (npm run admin). Quando uma versão nova
 * do sistema precisa de tabelas ou colunas novas, a API se ajusta sozinha: na primeira vez
 * que o login de um pedido esbarra numa coluna que falta, ela roda os comandos abaixo e
 * tenta de novo. Assim publicar o site basta, sem rodar nada à mão no banco.
 *
 * Os comandos são os mesmos do fim de db/schema.sql (um teste confere) e podem rodar mais de
 * uma vez. O arquivo .sql não vai junto com a função publicada, por isso eles ficam aqui.
 */
import type { Sql } from "./db.ts";

export const UPGRADE: string[] = [
  `CREATE TABLE IF NOT EXISTS volunteer_notes (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_id INTEGER NOT NULL REFERENCES volunteers(id) ON DELETE CASCADE,
    body         TEXT    NOT NULL CHECK (length(body) BETWEEN 1 AND 1000),
    author       TEXT    NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
)`,
  `CREATE INDEX IF NOT EXISTS volunteer_notes_volunteer ON volunteer_notes (volunteer_id, created_at DESC)`,
  `CREATE TABLE IF NOT EXISTS activity_log (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor    TEXT NOT NULL,
    action   TEXT NOT NULL,
    target   TEXT,
    team     TEXT,
    summary  TEXT NOT NULL,
    details  JSONB,
    repeats  INTEGER NOT NULL DEFAULT 1
)`,
  `CREATE INDEX IF NOT EXISTS activity_log_at ON activity_log (id DESC)`,
  `CREATE INDEX IF NOT EXISTS activity_log_actor ON activity_log (actor, id DESC)`,
  // por último: são as colunas que o login lê em todo pedido (ver db/schema.sql)
  `ALTER TABLE app_users ADD COLUMN IF NOT EXISTS suspended BOOLEAN NOT NULL DEFAULT FALSE`,
  `ALTER TABLE app_users ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ`,
];

/** Erro do Postgres de tabela (42P01) ou coluna (42703) que não existe. */
export function isMissingSchema(e: unknown): boolean {
  const code = (e as { code?: unknown } | null)?.code;
  return code === "42P01" || code === "42703";
}

export async function upgradeSchema(sql: Sql): Promise<void> {
  for (const statement of UPGRADE) await sql.query(statement);
}
